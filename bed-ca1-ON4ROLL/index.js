//////////////////////////////////////////////////////
// INCLUDES
//////////////////////////////////////////////////////
const app = require("./src/app");

//////////////////////////////////////////////////////
// HOMEPAGE ROUTE
//////////////////////////////////////////////////////
app.get("/", (req, res) => {
  res.status(200).json({
    message: "BED-CA1 API is running"
  });
});

//////////////////////////////////////////////////////
// SETUP ENVIRONMENT
//////////////////////////////////////////////////////
const PORT = process.env.PORT || 3000;

//////////////////////////////////////////////////////
// START SERVER
//////////////////////////////////////////////////////
app.listen(PORT, "0.0.0.0", () => {
  console.log(`App listening on port ${PORT}`);
});
